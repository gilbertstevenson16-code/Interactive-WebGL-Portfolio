import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { execFileSync } from "node:child_process";
const output = path.resolve(
  process.argv[2] || "artifacts/interactive-webgl-portfolio-source.zip",
);
const staging = await fs.mkdtemp(path.join(os.tmpdir(), "portfolio-source-"));
const entries = [
  "src",
  "scripts",
  "docs",
  "README.md",
  "AGENTS.md",
  "AI_START_HERE.md",
  "PROMPT.md",
  "THIRD_PARTY.md",
  "package.json",
  "package-lock.json",
  "tsconfig.json",
  "next.config.mjs",
  "postcss.config.mjs",
  "tailwind.config.ts",
  "eslint.config.mjs",
  ".gitignore",
];
for (const entry of entries)
  await fs.cp(entry, path.join(staging, entry), { recursive: true });
// Generated CSS is regenerated by predev/build; it is not canonical source.
await fs.rm(path.join(staging, "src/app/reference.css"), { force: true });
const forbidden =
  /\.(woff2?|ttf|otf|png|jpe?g|avif|webp|ico|glb|gltf|ktx2|mp4|wasm|bin|zip)$/i;
async function inspect(directory) {
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    if (
      entry.name === ".git" ||
      entry.name === "node_modules" ||
      entry.name.startsWith(".env") ||
      entry.isSymbolicLink() ||
      forbidden.test(entry.name)
    )
      throw Error("Excluded content: " + entry.name);
    if (entry.isDirectory()) await inspect(path.join(directory, entry.name));
  }
}
await inspect(staging);
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.rm(output, { force: true });
execFileSync("zip", ["-qr", output, ...entries], { cwd: staging });
console.log("Source ZIP:", output);
